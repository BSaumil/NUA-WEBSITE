#!/usr/bin/env node
/**
 * Every published image must be traceable to the generated manifest.
 *
 * The asset pack contains a 10_REFERENCE_ONLY folder marked "DO NOT USE
 * WITHOUT REVIEW". tools/images/build-derivatives.py refuses to convert it, but
 * that only stops the supported path — someone can still drop a file into
 * public/img/ by hand, and nothing downstream would notice.
 *
 * So rather than blacklisting the reference folder by name, this asserts the
 * stronger property: every file under public/img/ was produced by the
 * generator and is claimed by the manifest. An unrecognised file fails,
 * whatever it is and however it arrived.
 *
 * The reverse direction is checked too: a manifest entry whose file is missing
 * would render as a broken image in production, and is just as much a defect.
 */
const fs = require("fs");
const path = require("path");

const FRONTEND = path.resolve(__dirname, "..");
const IMG_DIR = path.join(FRONTEND, "public", "img");
const MANIFEST = path.join(FRONTEND, "src", "data", "imageManifest.js");

function fail(lines) {
  console.error("check-image-provenance: FAILED\n");
  for (const l of lines) console.error(`  ${l}`);
  console.error(
    "\nEvery file under public/img/ must be generated by " +
      "tools/images/build-derivatives.py and listed in imageManifest.js.\n" +
      "If you added an image by hand, run the generator instead."
  );
  process.exit(1);
}

if (!fs.existsSync(IMG_DIR)) {
  console.log("check-image-provenance: no public/img yet — nothing to check.");
  process.exit(0);
}

const source = fs.readFileSync(MANIFEST, "utf8");
const match = source.match(/const imageManifest = (\{[\s\S]*?\});\s*\n/);
if (!match) fail([`could not parse ${path.relative(FRONTEND, MANIFEST)}`]);

const manifest = JSON.parse(match[1]);

// Everything the manifest says should exist, as repo-relative public paths.
const expected = new Set();
for (const [group, entries] of Object.entries(manifest)) {
  for (const entry of entries) {
    for (const w of entry.widths) {
      expected.add(`${group}/${entry.id}-${w}.webp`);
    }
  }
}

// Everything actually on disk.
const actual = new Set();
for (const group of fs.readdirSync(IMG_DIR)) {
  const dir = path.join(IMG_DIR, group);
  if (!fs.statSync(dir).isDirectory()) {
    actual.add(group);
    continue;
  }
  for (const file of fs.readdirSync(dir)) actual.add(`${group}/${file}`);
}

const unexpected = [...actual].filter((f) => !expected.has(f)).sort();
const missing = [...expected].filter((f) => !actual.has(f)).sort();

const problems = [];
if (unexpected.length) {
  problems.push(`${unexpected.length} file(s) on disk that the manifest does not claim:`);
  for (const f of unexpected.slice(0, 20)) problems.push(`    public/img/${f}`);
  if (unexpected.length > 20) problems.push(`    … and ${unexpected.length - 20} more`);
}
if (missing.length) {
  if (problems.length) problems.push("");
  problems.push(`${missing.length} manifest entr(y/ies) with no file on disk:`);
  for (const f of missing.slice(0, 20)) problems.push(`    public/img/${f}`);
  if (missing.length > 20) problems.push(`    … and ${missing.length - 20} more`);
}

if (problems.length) fail(problems);

console.log(
  `check-image-provenance: OK — ${expected.size} files across ` +
    `${Object.keys(manifest).length} groups, all accounted for.`
);
